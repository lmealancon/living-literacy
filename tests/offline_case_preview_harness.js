'use strict';
const assert = require('assert');
const fs = require('fs');
const vm = require('vm');
const lesson = JSON.parse(fs.readFileSync('content/SYNTHETIC_WORD_STUDY.demo-1.json', 'utf8'));
const previewCode = fs.readFileSync('tools/offline-case-preview.js', 'utf8');
const clientCode = fs.readFileSync('prototype/web/investigation-client.js', 'utf8');

function setup(protocol='file:', withLesson=true) {
  const originalFetch = () => { throw new Error('A preview must not contact a network'); };
  const window = {location:{protocol}, fetch:originalFetch};
  if (withLesson) window.__LIVING_PREVIEW_LESSON__ = lesson;
  const context = vm.createContext({window});
  vm.runInContext(previewCode,context);
  vm.runInContext(clientCode,context);
  return {window,originalFetch};
}
async function main() {
  const remote=setup('https:');
  assert.strictEqual(remote.window.fetch,remote.originalFetch,'the simulator must never install on a deployed site');
  assert.equal((await setup('file:',false).window.fetch('/api/me')).status,503);
  const {window}=setup();
  const get=async path=>{const r=await window.fetch(path);return {status:r.status,body:await r.json()};};
  const post=async (path,body)=>{const r=await window.fetch(path,{method:'POST',body:JSON.stringify(body)});return {status:r.status,body:await r.json()};};
  const request=async (path,data)=>{const r=data===undefined?await get(path):await post(path,data);if(r.status<200||r.status>=300){const e=new Error('preview denied');e.status=r.status;throw e;}return r.body;};
  assert.equal((await window.fetch('https://example.test/private')).status,403);
  assert.equal((await get('/api/me')).body.identity,'synthetic-parent-1');
  assert.equal((await get('/api/profiles')).body.profiles[0].id,'synthetic-student-1');
  const casePath='/api/profiles/synthetic-student-1/investigation';
  assert.equal((await post(casePath,{action:'visit',revision:0,destination:'voice',extra:'forbidden'})).status,400);
  assert.equal((await post(casePath,{action:'visit',revision:99,destination:'voice'})).status,409);
  const navigated=[], errors=[];
  const client=window.LivingInvestigationClient.create({request,navigate:(...args)=>navigated.push(args),onError:e=>errors.push(e)});
  assert.equal(await client.load('synthetic-student-1'),true);
  assert.equal(client.snapshot().step,'post_office');
  assert.equal(await client.visit('activities'),false,'later locations are locked');
  assert.equal(await client.visit('voice'),true);
  assert.equal(await client.hint('decode'),true);
  assert.equal(client.snapshot().pendingHint,true);
  assert.equal(await client.attempt('decode','b',false),false);
  assert(client.snapshot().feedback.includes('try again'));
  client.reset();
  assert.equal(await client.load('synthetic-student-1'),true,'resume reloads preview case');
  assert.equal(client.snapshot().step,'decode');
  assert.equal(client.snapshot().pendingHint,true,'hint survives retry and reload');
  assert.equal(await client.attempt('decode','a',false),true);
  assert.equal(client.snapshot().clues[0].usedHint,true);
  assert.equal(await client.visit('activities'),true);
  assert.equal(await client.attempt('context','b',false),true);
  assert.equal(client.snapshot().step,'lesson');
  assert.equal(navigated.at(-1)[0],'activities');
  const data={student_id:'synthetic-student-1',lesson_id:lesson.lesson_id,version:lesson.version,idempotency_key:'preview-test-key'};
  const first=await post('/api/sessions',data);
  assert.equal(first.status,201);
  assert.equal((await post('/api/sessions',data)).body.session.session_id,first.body.session.session_id);
  assert.equal(await client.bindSession(first.body.session,'synthetic-student-1'),true);
  let session=first.body.session;
  async function action(name,extra={}) {
    const response=await post('/api/sessions/'+session.session_id+'/action',{action:name,revision:session.revision,...extra});
    assert.equal(response.status,200);session=response.body.session;
  }
  await action('activate');
  for(let i=0;i<5;i++)await action('next');
  await action('complete');
  const beforeMissing=client.snapshot().revision;
  assert.equal(await client.observeSession(session),true,'a completed but missing practice response returns a retry state');
  assert.equal(client.snapshot().step,'lesson');
  assert.equal(client.snapshot().revision,beforeMissing+1);
  assert.equal(client.snapshot().boundSessionId,null);
  assert.equal(client.snapshot().clues.length,2);
  assert(client.snapshot().message.includes('answer its Practice step'));
  session=(await post('/api/sessions',{...data,idempotency_key:'preview-test-key-2'})).body.session;
  assert.equal(await client.bindSession(session,'synthetic-student-1'),true);
  await action('activate');await action('next');await action('next');await action('next');
  await action('respond',{response:'mop',assisted:false});
  await action('next');await action('next');await action('complete');
  assert.equal(await client.observeSession(session),true,'a wrong practice word also returns a retry state');
  assert.equal(client.snapshot().step,'lesson');
  assert.equal(client.snapshot().boundSessionId,null);
  assert.equal(client.snapshot().clues.length,2);
  session=(await post('/api/sessions',{...data,idempotency_key:'preview-test-key-3'})).body.session;
  assert.equal(await client.bindSession(session,'synthetic-student-1'),true);
  await action('activate');
  await action('next');await action('next');await action('next');
  assert.equal(session.stage_index,3);
  assert.equal((await post('/api/sessions/'+session.session_id+'/action',{action:'respond',revision:session.revision,response:'',assisted:false})).status,403);
  await action('respond',{response:'map',assisted:false});
  await action('next');await action('next');await action('complete');
  assert.equal(await client.observeSession(session),true);
  assert.equal(client.snapshot().step,'bookshop');
  assert.equal(client.returnToWorld(),true);
  assert.equal(await client.visit('signin'),true);
  assert.equal(await client.attempt('sequence','c',false),true);
  assert.equal(client.snapshot().phase,'case_solved');
  assert.equal(client.snapshot().clues.length,3);
  assert.equal((await post('/api/logout',{})).status,200);
  assert.equal((await get(casePath)).status,403);
  assert.equal((await post('/api/login',{identity:'synthetic-parent-1',passphrase:'preview'})).status,200);
  assert.equal(await client.load('synthetic-student-1'),true);
  assert.equal(client.snapshot().phase,'case_solved','logout and login preserve this tab’s in-memory case');
  assert.equal(await client.restart(),true);
  assert.equal(client.snapshot().step,'post_office');
  console.log('Offline fictional case preview checks passed');
}
main().catch(error=>{console.error(error);process.exitCode=1;});
